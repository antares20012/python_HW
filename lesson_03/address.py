class Address:
    def __init__(self, index, city, street_name, building, apartment_number):
        self.index = index                          #Почтовый индекс
        self.city = city                            #Город
        self.street_name = street_name              #Название улицы
        self.building = building                    #Номер дома
        self.apartment_number = apartment_number    #Номер квартиры



